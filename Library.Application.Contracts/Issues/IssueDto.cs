namespace Library.Application.Contracts.Issues;

/// <summary>
/// DTO для отображения информации о выдаче книги читателю.
/// Используется в GET запросах и содержит полную информацию о выданной книге,
/// читателе, сроках выдачи и возврата.
/// </summary>
public class IssueDto
{
    /// <summary>
    /// Уникальный идентификатор записи о выдаче.
    /// Это значение установлено клиентом при создании и хранится в БД.
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// Уникальный идентификатор выданной книги (должен быть > 0).
    /// </summary>
    public int BookId { get; set; }

    /// <summary>
    /// Название выданной книги (например: "Война и мир").
    /// Загружается из данных книги при получении выдачи.
    /// Обязательное поле, максимум 255 символов.
    /// </summary>
    public required string BookTitle { get; set; }

    /// <summary>
    /// Уникальный идентификатор читателя (должен быть > 0).
    /// </summary>
    public int ReaderId { get; set; }

    /// <summary>
    /// Полное имя и фамилия читателя, который взял книгу (например: "Иван Петров").
    /// Загружается из данных читателя при получении выдачи.
    /// Обязательное поле, максимум 150 символов.
    /// </summary>
    public required string ReaderFullName { get; set; }

    /// <summary>
    /// Дата и время выдачи книги читателю (UTC).
    /// </summary>
    public DateTime IssueDate { get; set; }

    /// <summary>
    /// Количество дней, на которые была выдана книга (например: 14 дней).
    /// Используется для расчета планового срока возврата.
    /// Должен быть в диапазоне 1-30 дней.
    /// </summary>
    public int DaysCount { get; set; }

    /// <summary>
    /// Фактическая дата и время возврата книги читателем (UTC).
    /// Может быть null если книга еще не возвращена.
    /// Критично для отслеживания статуса выдачи и проверки просроченных книг.
    /// </summary>
    public DateTime? ReturnDate { get; set; }
}
