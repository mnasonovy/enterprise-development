namespace Library.Application.Contracts.Books;

/// <summary>
/// DTO для передачи данных о книге между слоями приложения.
/// Используется при получении информации о книге с полными данными типа, издателя и авторов.
/// </summary>
public class BookDto
{
    /// <summary>
    /// Уникальный идентификатор книги.
    /// Это значение установлено клиентом при создании и хранится в БД.
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// Название книги (например: "Война и мир", "Преступление и наказание").
    /// Обязательное поле, максимум 255 символов.
    /// </summary>
    public required string Title { get; set; }

    /// <summary>
    /// Год публикации/издания книги (например: 2024, 1869, 1455).
    /// Должен быть в разумном диапазоне (1000-2100).
    /// </summary>
    public int Year { get; set; }


    /// <summary>
    /// Буквенно-цифровой каталожный код книги (например: "А1", "Б2-В3").
    /// Используется для физической организации книг в библиотеке.
    /// Необязательное поле, максимум 50 символов.
    /// </summary>
    public string? AlphabetCode { get; set; }

    /// <summary>
    /// Название типа книги (например: "Роман", "Учебник", "Справочник").
    /// Заполняется автоматически при преобразовании из Domain модели.
    /// </summary>
    public required string BookTypeName { get; set; }

    /// <summary>
    /// Название издателя книги (например: "Penguin Random House", "AST").
    /// Заполняется автоматически при преобразовании из Domain модели.
    /// </summary>
    public required string PublisherName { get; set; }

    /// <summary>
    /// Коллекция имён авторов (инициалы + фамилия, например: "И. П. Петров").
    /// Может быть пусто, если авторы не добавлены.
    /// </summary>
    public List<string> AuthorNames { get; set; } = [];
}
