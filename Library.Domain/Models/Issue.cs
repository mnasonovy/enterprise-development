namespace Library.Domain.Models;

/// <summary>
/// Представляет запись о выдаче книги читателю библиотеки.
/// Содержит информацию о том, когда, кому и на сколько дней была выдана книга.
/// Отслеживает статус выдачи и возврата книги.
/// </summary>
public class Issue
{
    /// <summary>
    /// Уникальный идентификатор записи о выдаче в базе данных.
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// Уникальный идентификатор книги.
    /// Используется как внешний ключ для связи с таблицей Book.
    /// </summary>
    public int BookId { get; set; }

    /// <summary>
    /// Книга, которая была выдана читателю.
    /// Обязательное поле. Представляет справочную сущность с полной информацией о книге.
    /// </summary>
    public required Book Book { get; set; }

    /// <summary>
    /// Уникальный идентификатор читателя.
    /// Используется как внешний ключ для связи с таблицей Reader.
    /// </summary>
    public int ReaderId { get; set; }

    /// <summary>
    /// Читатель, который взял книгу из библиотеки.
    /// Обязательное поле. Представляет справочную сущность с информацией о читателе.
    /// </summary>
    public required Reader Reader { get; set; }

    /// <summary>
    /// Дата и время выдачи книги читателю.
    /// Обязательное поле. Используется для расчета срока возврата и отслеживания выданных книг.
    /// </summary>
    public DateTime IssueDate { get; set; }

    /// <summary>
    /// Количество дней, на которые выдана книга.
    /// Обязательное поле. Используется для расчета планового срока возврата.
    /// </summary>
    public int DaysCount { get; set; }

    /// <summary>
    /// Фактическая дата и время возврата книги читателем.
    /// Может быть <c>null</c> если книга еще не возвращена.
    /// Используется для отслеживания статуса выдачи и проверки просроченных книг.
    /// </summary>
    public DateTime? ReturnDate { get; set; }
}